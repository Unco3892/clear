def create_combined_plot(data_qgloss, data_nciw, subdir_name, args, 
                         common_ordered_methods, common_method_display_map, common_palette,
                         project_base_dir, metric_display_names, upper_plot_show_xlabels=False,
                         consistent_dataset_order=None):
    """
    Creates a combined plot with Quantile Loss on top and NCIW at the bottom, sharing X-axis and legend.
    
    Args:
        data_qgloss: DataFrame with quantile loss data
        data_nciw: DataFrame with NCIW data
        subdir_name: Name of the subdirectory for file naming
        args: Command line arguments
        common_ordered_methods: List of methods to display in a specific order
        common_method_display_map: Mapping from internal method names to display names
        common_palette: Color palette for methods
        project_base_dir: Base directory of the project
        metric_display_names: Mapping from metric keys to display names
        upper_plot_show_xlabels: Whether to show x-axis labels on the upper plot (default: False)
        consistent_dataset_order: Optional consistent dataset order for all plots
    """
    print(f"\n--- Generating Combined Plot for {subdir_name} ---")

    # First normalize both datasets
    metric_key_qgloss = "quantileloss"
    metric_name_qgloss = metric_display_names.get(metric_key_qgloss, metric_key_qgloss)
    print(f"  Processing {metric_name_qgloss} for combined plot...")
    norm_data_qgloss = normalize_data(data_qgloss, baseline_method=args.baseline, method_display_map=common_method_display_map)
    
    metric_key_nciw = "nciw"
    metric_name_nciw = metric_display_names.get(metric_key_nciw, metric_key_nciw)
    print(f"  Processing {metric_name_nciw} for combined plot...")
    norm_data_nciw = normalize_data(data_nciw, baseline_method=args.baseline, method_display_map=common_method_display_map)
    
    # Check if we have both datasets with normalized data
    if norm_data_qgloss.empty or norm_data_nciw.empty:
        print(f"    WARNING: Missing normalized data for either {metric_name_qgloss} or {metric_name_nciw} in {subdir_name}. Skipping combined plot.")
        return
    
    # Create a common dataset order based on maximum normalized value of both metrics
    # or use the provided consistent_dataset_order if available
    datasets_in_qgloss = set(norm_data_qgloss['Dataset'].unique())
    datasets_in_nciw = set(norm_data_nciw['Dataset'].unique())
    common_datasets = datasets_in_qgloss.intersection(datasets_in_nciw)
    
    if not common_datasets:
        print(f"    WARNING: No common datasets between {metric_name_qgloss} and {metric_name_nciw} in {subdir_name}. Skipping combined plot.")
        return
    
    if consistent_dataset_order is not None:
        # Filter the consistent order to only include datasets present in both metrics
        valid_datasets = [d for d in consistent_dataset_order if d in common_datasets]
        
        if valid_datasets:
            print(f"  Using consistent dataset order for combined plot: {valid_datasets}")
            sorted_datasets = valid_datasets
        else:
            # Fallback to computing order if no overlap between consistent order and common datasets
            print(f"  No overlap between consistent order and common datasets. Computing custom order.")
            # Generate a custom order based on max of both metrics
            common_dataset_max_values = {}
            for dataset in common_datasets:
                qgloss_max = norm_data_qgloss[norm_data_qgloss['Dataset'] == dataset]['normalized_mean'].max()
                nciw_max = norm_data_nciw[norm_data_nciw['Dataset'] == dataset]['normalized_mean'].max()
                common_dataset_max_values[dataset] = max(qgloss_max, nciw_max)
            sorted_datasets = sorted(common_dataset_max_values.keys(), key=lambda x: common_dataset_max_values[x])
    else:
        # Generate a custom order based on max of both metrics
        common_dataset_max_values = {}
        for dataset in common_datasets:
            qgloss_max = norm_data_qgloss[norm_data_qgloss['Dataset'] == dataset]['normalized_mean'].max()
            nciw_max = norm_data_nciw[norm_data_nciw['Dataset'] == dataset]['normalized_mean'].max()
            common_dataset_max_values[dataset] = max(qgloss_max, nciw_max)
        
        # Sort datasets by their maximum normalized value across both metrics
        sorted_datasets = sorted(common_dataset_max_values.keys(), key=lambda x: common_dataset_max_values[x])
    
    print(f"  Common dataset order for both plots: {sorted_datasets}")
    
    # Filter both DataFrames to include only common datasets
    norm_data_qgloss = norm_data_qgloss[norm_data_qgloss['Dataset'].isin(common_datasets)].copy()
    norm_data_nciw = norm_data_nciw[norm_data_nciw['Dataset'].isin(common_datasets)].copy()
    
    # Assign dataset index based on our custom sorting
    for i, dataset_name in enumerate(sorted_datasets):
        norm_data_qgloss.loc[norm_data_qgloss['Dataset'] == dataset_name, 'dataset_index'] = i
        norm_data_nciw.loc[norm_data_nciw['Dataset'] == dataset_name, 'dataset_index'] = i
    
    # Check if we still have data after filtering
    if norm_data_qgloss.empty or norm_data_nciw.empty:
        print(f"    WARNING: One or both metrics have no data after filtering for common datasets. Skipping combined plot.")
        return

    # Create figure with precise control of spacing
    fig = plt.figure(figsize=(12, 14))
    
    # Apply global styling once
    apply_consistent_font_settings()
    
    # Create the two plots with more precise control and clear separation
    # Top plot takes 45% of the height, bottom takes 45%, leaving 10% for spacing and legend
    ax_top = fig.add_axes([0.1, 0.55, 0.85, 0.4])  # [left, bottom, width, height]
    ax_bottom = fig.add_axes([0.1, 0.1, 0.85, 0.4])
    
    # --- Quantile Loss (Top Plot) ---
    print(f"  Creating top plot for {metric_name_qgloss}...")
    # Use consistent inset positioning for top and bottom plots
    # For the top plot's inset, position it at the same relative location as bottom plot's inset
    inset_config_top = {
        'subplot_y_bottom': 0.48, 
        'subplot_height': 0.5, 
        'is_part_of_combined': True
    }
    _f, _at, _ai_top, (handles_top, labels_top) = create_plot(
        norm_data_qgloss, metric_name=metric_name_qgloss,
        ordered_methods=common_ordered_methods, y_axis_from_zero=args.y_axis_from_zero,
        error_bar_type=args.error_bar_type, palette=common_palette,
        baseline_internal_name=args.baseline,
        fig_to_use=fig, ax_to_use=ax_top,
        make_legend=False,
        save_fig_if_internal=False,
        inset_config_from_caller=inset_config_top,
        set_styling_if_creating_fig=False,
        output_format=args.output_format,
        predefined_dataset_order=sorted_datasets,  # Use the common sorted order
        subdirectory_name=subdir_name  # Pass subdirectory name for label positioning
    )
    
    # --- NCIW (Bottom Plot) ---
    print(f"  Creating bottom plot for {metric_name_nciw}...")
    # Use consistent inset positioning relative to subplot
    inset_config_bottom = {
        'subplot_y_bottom': 0.03, 
        'subplot_height': 0.5, 
        'is_part_of_combined': True
    }
    _f, _ab, _ai_bottom, (handles_bottom, labels_bottom) = create_plot(
        norm_data_nciw, metric_name=metric_name_nciw,
        ordered_methods=common_ordered_methods, y_axis_from_zero=args.y_axis_from_zero,
        error_bar_type=args.error_bar_type, palette=common_palette,
        baseline_internal_name=args.baseline,
        fig_to_use=fig, ax_to_use=ax_bottom,
        make_legend=False,
        save_fig_if_internal=False,
        inset_config_from_caller=inset_config_bottom,
        set_styling_if_creating_fig=False,
        output_format=args.output_format,
        predefined_dataset_order=sorted_datasets,  # Use the common sorted order
        subdirectory_name=subdir_name  # Pass subdirectory name for label positioning
    )
    
    # Update tick labels for each inset plot individually.
    # Y-axis limits are determined by create_plot for each inset, allowing them to be dynamic.
    if _ai_top is not None:
        # The y-limits are already set by create_plot. We just update tick labels based on its current limits.
        # If further adjustments to y-limits (e.g., enforcing a global min/max or min span) were needed,
        # they could be applied here before updating tick labels.
        yticks_inset_top = _ai_top.get_yticks()
        _ai_top.set_yticks(yticks_inset_top) # Ensure ticks are based on the final ylim
        _ai_top.set_yticklabels([f"{int(y)}%" for y in yticks_inset_top], 
                               fontsize=10 if inset_config_top.get('is_part_of_combined') else 12)
    
    if _ai_bottom is not None:
        # The y-limits are already set by create_plot. We just update tick labels.
        yticks_inset_bottom = _ai_bottom.get_yticks()
        _ai_bottom.set_yticks(yticks_inset_bottom) # Ensure ticks are based on the final ylim
        _ai_bottom.set_yticklabels([f"{int(y)}%" for y in yticks_inset_bottom], 
                                   fontsize=10 if inset_config_bottom.get('is_part_of_combined') else 12)

    # Ensure both plots have exactly the same y-axis minimum value
    if not args.y_axis_from_zero:
        # Force both plots to have exactly 0.65 as minimum (lower than before)
        min_y_value = 0.65
        
        # Set both plots to the same y-minimum
        y_min_top, y_max_top = ax_top.get_ylim()
        y_min_bottom, y_max_bottom = ax_bottom.get_ylim()
        
        ax_top.set_ylim(min_y_value, y_max_top)
        ax_bottom.set_ylim(min_y_value, y_max_bottom)
        
        # Explicitly set ticks to include the minimum value and avoid duplicates
        for ax in [ax_top, ax_bottom]:
            current_ticks = ax.get_yticks()
            filtered_ticks = [t for t in current_ticks if not (t > min_y_value and t < min_y_value + 0.1)]
            if min_y_value not in filtered_ticks and not np.any(np.isclose(filtered_ticks, min_y_value, rtol=0, atol=0.001)):
                filtered_ticks = np.append(filtered_ticks, min_y_value)
            filtered_ticks = np.sort(filtered_ticks)
            ax.set_yticks(filtered_ticks)
            
        # Force both plots to use the exact same tick set (taking from bottom plot)
        bottom_ticks = ax_bottom.get_yticks()
        ax_top.set_yticks(bottom_ticks)
    
    # Now set up the x-axis ticks and labels for both plots to ensure consistency
    x_ticks = list(range(len(sorted_datasets)))
    x_limits = (-0.5, len(sorted_datasets) - 0.5)
    
    # Configure bottom plot x-axis (always shows labels)
    ax_bottom.set_xlim(x_limits)
    ax_bottom.set_xticks(x_ticks)
    ax_bottom.set_xticklabels(sorted_datasets, rotation=45, ha='right', fontsize=14)
    
    # Configure top plot x-axis
    ax_top.set_xlim(x_limits)
    ax_top.set_xticks(x_ticks)
    
    # Show or hide x-axis labels on top plot based on parameter
    if upper_plot_show_xlabels:
        ax_top.set_xticklabels(sorted_datasets, rotation=45, ha='right', fontsize=14)
    else:
        ax_top.set_xticklabels([])  # Empty labels to hide them
        ax_top.set_xlabel('')  # No x-label needed
    
    # Create shared legend precisely centered between the plots
    if handles_top:
        legend_ncol = max(1, len(handles_top) // 2 if len(handles_top) > 4 else len(handles_top))
        # Position legend in the middle space between plots
        legend = fig.legend(
            handles=handles_top, labels=labels_top,
            loc='center', bbox_to_anchor=(0.5, 0.525), 
            ncol=legend_ncol, frameon=True, 
            fancybox=True, edgecolor='black', 
            fontsize=14, borderaxespad=0
        )
    
    # Save combined figure
    figures_output_dir = os.path.join(project_base_dir, "plots", "real")
    os.makedirs(figures_output_dir, exist_ok=True) # Ensure it exists
    
    combined_output_file_base = os.path.join(figures_output_dir, f"{subdir_name}_{args.output_file_prefix}_combined")
    
    # Save according to the selected output format
    if args.output_format in ['pdf', 'both']:
        pdf_file = f"{combined_output_file_base}.pdf"
        plt.savefig(pdf_file, dpi=600, bbox_inches='tight')
        print(f"Combined figure saved to {pdf_file}")
    
    if args.output_format in ['png', 'both']:
        png_file = f"{combined_output_file_base}.png"
        plt.savefig(png_file, dpi=800, bbox_inches='tight')
        print(f"Combined figure saved to {png_file}")

    plt.close(fig) # Close the figure to free memory
    print(f"--- Finished Combined Plot for {subdir_name} ---")

