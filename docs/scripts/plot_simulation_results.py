def plot_1d_simulation_results_symmetric_from_csv(
    positive_distances,
    avg_coverage_metrics_dict, # {'CLEAR': array, 'EPISTEMIC': array, ...}
    avg_width_metrics_dict,    # {'CLEAR': array, 'EPISTEMIC': array, ...}
    target_coverage,
    output_path_base, # Base path and filename, e.g., "plots/sim_d1_homo"
    title_suffix,
    is_d1_homo_special_case=False
):
    """
    Generates a 1D plot similar to the R-generated image, symmetric around x=0.
    Takes data prepared from CSV files.
    """
    x_plot = np.concatenate((-positive_distances[::-1], positive_distances))
    
    fig, axes = plt.subplots(1, 2, figsize=(12, 5.5)) # Adjusted figsize for legend
    
    # Define original order, colors, and display names
    all_method_keys_original_order = ['CLEAR', 'PCS', 'CQR', 'S-Naive']
    colors_map = {'CLEAR': 'red', 'PCS': 'blue', 'CQR': 'green', 'S-Naive': 'purple'}
    display_names_map = {'CLEAR': 'CLEAR', 'PCS': 'PCS-EPISTEMIC', 'CQR': 'ALEATORIC-R', 'S-Naive': 'Naive'}

    # Start with all methods and their data
    methods_to_plot = [m for m in all_method_keys_original_order if m in avg_coverage_metrics_dict]

    # Conditional removal of 'S-Naive' for fixed d=1, homo noise plot
    if is_d1_homo_special_case:
        print("Modifying plot data for d=1, homo noise: Removing 'S-Naive' method.")
        if 'S-Naive' in avg_coverage_metrics_dict: avg_coverage_metrics_dict.pop('S-Naive', None)
        if 'S-Naive' in avg_width_metrics_dict: avg_width_metrics_dict.pop('S-Naive', None)
        if 'S-Naive' in methods_to_plot: methods_to_plot.remove('S-Naive')

    # Coverage subplot (axes[0])
    for method_key in methods_to_plot:
        if method_key in avg_coverage_metrics_dict:
            coverage_values = avg_coverage_metrics_dict[method_key]
            plot_coverage = np.concatenate((coverage_values[::-1], coverage_values))
            axes[0].plot(x_plot, plot_coverage, color=colors_map[method_key], label=display_names_map.get(method_key, method_key), linewidth=2.5)
    
    axes[0].axhline(target_coverage, color='black', linestyle='--', linewidth=1)
    axes[0].set_xlabel('x')
    axes[0].set_ylabel('Conditional Coverage')
    axes[0].set_ylim([0.35, 1.05])
    axes[0].grid(True, alpha=0.3, linestyle=':')

    # Width subplot (axes[1])
    max_width_plot = 0
    for method_key in methods_to_plot:
        if method_key in avg_width_metrics_dict:
            width_values = avg_width_metrics_dict[method_key]
            plot_width = np.concatenate((width_values[::-1], width_values))
            axes[1].plot(x_plot, plot_width, color=colors_map[method_key], label=display_names_map.get(method_key, method_key), linewidth=2.5)
            if len(plot_width) > 0:
                 max_width_plot = max(max_width_plot, np.nanmax(plot_width[np.isfinite(plot_width)]))

    axes[1].set_xlabel('x')
    axes[1].set_ylabel('Average width')
    if max_width_plot > 0:
        axes[1].set_ylim(bottom=0, top=30) # Cap at 30
    else:
        axes[1].set_ylim(bottom=0, top=25)
    axes[1].grid(True, alpha=0.3, linestyle=':')

    # Shared legend below plots
    handles, labels = [], []
    # Get handles and labels from the axes
    # Use proxy artists for consistent legend matching original script
    proxy_handles = []
    for method_key in methods_to_plot:
        proxy_handles.append(mpl.lines.Line2D([0], [0], color=colors_map[method_key], lw=2.5, label=display_names_map[method_key]))

    fig.legend(handles=proxy_handles, loc='lower center', ncol=len(methods_to_plot),frameon=True, fancybox=True, edgecolor='black', fontsize=16)

    fig.suptitle(None) # No title for any output
    plt.tight_layout(rect=[0, 0.08, 1, 0.92])
    
    # Ensure output directory exists
    output_dir = os.path.dirname(output_path_base)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir)
        print(f"Created output directory: {output_dir}")

    png_output_path = output_path_base + ".png"
    pdf_output_path = output_path_base + ".pdf"

    plt.savefig(pdf_output_path, format='pdf')
    print(f"Saved 1D-style PDF plot: {pdf_output_path}")
    plt.savefig(png_output_path, dpi=800)
    print(f"Saved 1D-style PNG plot: {png_output_path}")
    plt.close(fig)

def plot_multivariate_results_from_csv(
    distances,
    avg_coverage_metrics_dict,
    avg_width_metrics_dict,
    target_coverage,
    output_path_base,
    title_suffix
):
    """
    Generates multivariate plots using clear.utils.plot_distance_metrics.
    Takes data prepared from CSV files.
    """
    all_method_keys_original_order = ['CLEAR', 'PCS', 'CQR', 'S-Naive']
    original_colors_map = {'CLEAR': 'red', 'PCS': 'blue', 'CQR': 'green', 'S-Naive': 'purple'}
    original_display_names_map = {'CLEAR': 'CLEAR', 'PCS': 'PCS-EPISTEMIC', 'CQR': 'ALEATORIC-R', 'S-Naive': 'Naive'}

    methods_to_plot_final = [m for m in all_method_keys_original_order if m in avg_coverage_metrics_dict]

    plot_colors_final = [original_colors_map[m] for m in methods_to_plot_final]
    plot_display_names_final = [original_display_names_map[m] for m in methods_to_plot_final]

    # Reconstruct metrics_plot_dict for plot_distance_metrics
    metrics_plot_dict_for_clear_utils = {
        method: {'distances': distances, 'coverage': avg_coverage_metrics_dict[method], 'width': avg_width_metrics_dict[method]}
        for method in methods_to_plot_final
    }

    fig, axes = plot_distance_metrics(
        metrics_plot_dict_for_clear_utils,
        methods_to_plot_final,
        plot_colors_final,
        plot_display_names_final,
        target_coverage=target_coverage
    )
    axes[1].set_ylim(bottom=0, top=30) # Cap width plot y-axis at 30
    
    fig.suptitle(None) # No title for any output

    for ax in axes:
        if ax.get_legend() is not None:
            ax.get_legend().remove()

    proxy_handles = []
    for i, method_key in enumerate(methods_to_plot_final):
        proxy_handles.append(mpl.lines.Line2D([0], [0], color=plot_colors_final[i], lw=2.5, label=plot_display_names_final[i]))
    
    fig.legend(handles=proxy_handles, loc='lower center', ncol=len(methods_to_plot_final),frameon=True, fancybox=True, edgecolor='black', fontsize=16)
    plt.tight_layout(rect=[0, 0.08, 1, 0.92])

    # Ensure output directory exists
    output_dir = os.path.dirname(output_path_base)
    if output_dir and not os.path.exists(output_dir):
        os.makedirs(output_dir)
        print(f"Created output directory: {output_dir}")

    png_output_path = output_path_base + ".png"
    pdf_output_path = output_path_base + ".pdf"

    plt.savefig(pdf_output_path, format='pdf')
    print(f"Saved multivariate PDF plot: {pdf_output_path}")
    plt.savefig(png_output_path, dpi=800)
    print(f"Saved multivariate PNG plot: {png_output_path}")
    plt.close(fig)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Plot benchmark simulation results from CSV files for predefined scenarios.")
    parser.add_argument('--sim_results_dir', type=str, default="plots/simulations",
                        help='Base directory where simulation CSV files are located, relative to project root.')
    parser.add_argument('--plot_output_dir', type=str, default="plots/simulations",
                        help='Base directory where generated plots will be saved, relative to project root.')
    parser.add_argument('--target_coverage', type=float, default=0.90,
                        help='Target coverage level for the plots.')
    parser.add_argument('--num_simulations', type=int, default=100,
                        help='Number of simulations run (used for title suffix context).')

    args = parser.parse_args()

    # Apply Matplotlib style settings (same as benchmark_simulations.py)
    plt.style.use('seaborn-v0_8-whitegrid')
    mpl.rcParams.update({
        "font.size": 14,
        "axes.labelsize": 16,
        "axes.titlesize": 17,
        "legend.fontsize": 14,
        "xtick.labelsize": 14,
        "ytick.labelsize": 14,
        "font.family": "serif",
        "font.serif": ["Palatino", "Times New Roman", "DejaVu Serif"],
    })

    # --- Define Scenarios ---
    # Epistemic mode is fixed as 'external_pcs_uq' based on user's example batch command
    # which implies --use_external_pcs was used for all simulations.
    fixed_epistemic_mode = "external_pcs_uq"

    scenarios_to_plot = [
        {
            "d_str": "1", "noise": "homo",
            "plot_type": "1d", "is_d1_homo_special": True,
        },
        {
            "d_str": "1", "noise": "hetero1",
            "plot_type": "1d", "is_d1_homo_special": False,
        },
        {
            "d_str": "1", "noise": "hetero2",
            "plot_type": "1d", "is_d1_homo_special": False,
        },
        {
            # For randomize_d, benchmark_simulations.py uses d_str="random"
            # and the example command specifies noise_type=homo
            "d_str": "random", "noise": "homo",
            "plot_type": "multivariate", "is_d1_homo_special": False,
        },
    ]

    # --- Loop Through Scenarios and Plot ---
    for scenario in scenarios_to_plot:
        print(f"\nProcessing scenario: d={scenario['d_str']}, noise={scenario['noise']}, epistemic={fixed_epistemic_mode}")

        # Construct paths
        # Input directory for this scenario's CSVs
        scenario_input_dir_name = f"d{scenario['d_str']}/{scenario['noise']}_{fixed_epistemic_mode}"
        full_scenario_input_dir = os.path.join(project_root, args.sim_results_dir, scenario_input_dir_name)

        coverage_csv_name = f"coverage_results_d{scenario['d_str']}_{scenario['noise']}_{fixed_epistemic_mode}.csv"
        width_csv_name = f"width_results_d{scenario['d_str']}_{scenario['noise']}_{fixed_epistemic_mode}.csv"
        
        coverage_csv_path = os.path.join(full_scenario_input_dir, coverage_csv_name)
        width_csv_path = os.path.join(full_scenario_input_dir, width_csv_name)

        # Output plot base path
        # Directory part for the output plots
        scenario_output_dir_name = f"d{scenario['d_str']}/{scenario['noise']}_{fixed_epistemic_mode}"
        full_scenario_output_plot_dir = os.path.join(project_root, args.plot_output_dir, scenario_output_dir_name)
        
        # Base filename for the output plots (without .png/.pdf extension)
        output_plot_filename_base = f"avg_metrics_d{scenario['d_str']}_{scenario['noise']}_{fixed_epistemic_mode}"
        output_path_base_for_plot_func = os.path.join(full_scenario_output_plot_dir, output_plot_filename_base)

        # Create output directory for plots if it doesn't exist (plotting functions also do this, but good practice)
        if not os.path.exists(full_scenario_output_plot_dir):
            os.makedirs(full_scenario_output_plot_dir)
            print(f"Created plot output directory: {full_scenario_output_plot_dir}")

        # Load data for the current scenario
        try:
            coverage_df = pd.read_csv(coverage_csv_path)
            width_df = pd.read_csv(width_csv_path)
        except FileNotFoundError:
            print(f"Warning: CSV files not found for scenario {scenario}. Skipping.")
            print(f"  Tried paths: {coverage_csv_path} and {width_csv_path}")
            continue
        except Exception as e:
            print(f"Warning: Error reading CSV files for scenario {scenario}: {e}. Skipping.")
            continue

        if 'distance' not in coverage_df.columns or 'distance' not in width_df.columns:
            print(f"Warning: 'distance' column missing in CSVs for scenario {scenario}. Skipping.")
            continue

        distances_data = coverage_df['distance'].values
        method_cols = ['CLEAR', 'PCS', 'CQR', 'S-Naive']
        avg_coverage_metrics = {}
        avg_width_metrics = {}

        for col in method_cols:
            if col in coverage_df.columns:
                avg_coverage_metrics[col] = coverage_df[col].values
            if col in width_df.columns:
                avg_width_metrics[col] = width_df[col].values

        if not avg_coverage_metrics or not avg_width_metrics:
            print(f"Warning: No method data found in CSVs for scenario {scenario}. Skipping.")
            continue
        
        # Construct title suffix (though not directly used for suptitle in current plot funcs)
        title_suffix = f"d={scenario['d_str']}, noise={scenario['noise']}, epistemic={fixed_epistemic_mode}, sims={args.num_simulations}"

        # Call the appropriate plotting function
        if scenario['plot_type'] == '1d':
            plot_1d_simulation_results_symmetric_from_csv(
                positive_distances=distances_data,
                avg_coverage_metrics_dict=avg_coverage_metrics,
                avg_width_metrics_dict=avg_width_metrics,
                target_coverage=args.target_coverage,
                output_path_base=output_path_base_for_plot_func,
                title_suffix=title_suffix,
                is_d1_homo_special_case=scenario['is_d1_homo_special']
            )
        elif scenario['plot_type'] == 'multivariate':
            plot_multivariate_results_from_csv(
                distances=distances_data,
                avg_coverage_metrics_dict=avg_coverage_metrics,
                avg_width_metrics_dict=avg_width_metrics,
                target_coverage=args.target_coverage,
                output_path_base=output_path_base_for_plot_func,
                title_suffix=title_suffix
            )
        else:
            print(f"Warning: Unknown plot_type '{scenario['plot_type']}' for scenario {scenario}. Skipping.")
            continue

    print("\nAll scenario plotting complete.") 